"""High-level local vault operations for API handlers."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from athanor_api.schemas.graph import ArchitectureGraph
from athanor_api.settings import settings
from athanor_api.vault.coverage import collect_graph_secret_names
from athanor_api.vault.store import VaultStore

_vault_service: LocalVaultService | None = None


class LocalVaultService:
    def __init__(self, store: VaultStore) -> None:
        self.store = store

    @property
    def vault_path(self) -> Path:
        return self.store.vault_path

    def status(self) -> dict[str, Any]:
        return self.store.status()

    def init(self, passphrase: str) -> dict[str, Any]:
        self.store.init(passphrase)
        return self.store.status()

    def unlock(self, passphrase: str) -> dict[str, Any]:
        self.store.unlock(passphrase)
        return self.store.status()

    def lock(self) -> dict[str, Any]:
        self.store.lock()
        return self.store.status()

    def list_entries(self) -> list[dict[str, Any]]:
        return self.store.list_entries()

    def put_entry(self, name: str, value: str, notes: str | None = None) -> dict[str, Any]:
        return self.store.put_entry(name, value, notes=notes)

    def delete_entry(self, name: str) -> None:
        self.store.delete_entry(name)

    def coverage(
        self,
        *,
        graph: ArchitectureGraph | None = None,
        names: list[str] | None = None,
    ) -> dict[str, Any]:
        requested = list(names or [])
        if graph is not None:
            requested.extend(collect_graph_secret_names(graph))
        # Preserve order, unique
        seen: set[str] = set()
        ordered: list[str] = []
        for name in requested:
            clean = name.strip()
            if not clean or clean in seen:
                continue
            seen.add(clean)
            ordered.append(clean)

        present: list[str] = []
        missing: list[str] = []
        unlocked = self.store.status()["unlocked"]
        vault_names: set[str] = set()
        if unlocked:
            vault_names = {item["name"] for item in self.store.list_entries() if item["hasValue"]}

        for name in ordered:
            if unlocked and name in vault_names:
                present.append(name)
            else:
                missing.append(name)

        return {
            "unlocked": unlocked,
            "requested": ordered,
            "present": present,
            "missing": missing,
        }

    def materialize_env(
        self,
        *,
        path: Path,
        names: list[str] | None = None,
        graph: ArchitectureGraph | None = None,
    ) -> dict[str, Any]:
        if not path.is_absolute():
            raise ValueError("Materialize path must be absolute")

        target = path
        if target.exists() and target.is_dir():
            target = target / ".env"
        elif target.suffix == "" and not target.name.startswith("."):
            # Treat extensionless path as a directory destination.
            target = target / ".env"

        target_names = list(names or [])
        if graph is not None:
            target_names.extend(collect_graph_secret_names(graph))
        seen: set[str] = set()
        ordered: list[str] = []
        for name in target_names:
            clean = name.strip()
            if not clean or clean in seen:
                continue
            seen.add(clean)
            ordered.append(clean)

        values = self.store.get_values(ordered if ordered else None)
        if ordered:
            written_names = [name for name in ordered if name in values]
            missing = [name for name in ordered if name not in values]
        else:
            written_names = sorted(values.keys())
            missing = []

        lines = [
            "# Generated by AthanorIDE local vault. Do not commit this file.",
            "# Values were materialized for local runs only.",
            "",
        ]
        for name in written_names:
            raw = values[name]
            escaped = raw.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            lines.append(f'{name}="{escaped}"')
        lines.append("")

        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("\n".join(lines), encoding="utf-8")
        try:
            target.chmod(0o600)
        except OSError:
            pass

        return {
            "path": str(target),
            "writtenCount": len(written_names),
            "writtenNames": written_names,
            "missing": missing,
        }


def get_vault_service() -> LocalVaultService:
    global _vault_service
    if _vault_service is None:
        vault_path = settings.data_dir / "vault" / "vault.v1.json.enc"
        store = VaultStore(vault_path, idle_ttl_seconds=settings.vault_idle_ttl_seconds)
        _vault_service = LocalVaultService(store)
    return _vault_service


def reset_vault_service_for_tests(service: LocalVaultService | None = None) -> None:
    """Test helper to inject/clear the singleton."""

    global _vault_service
    _vault_service = service
