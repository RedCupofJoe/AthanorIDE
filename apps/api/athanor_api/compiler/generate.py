"""Generate Python source from a TransformationSpec."""

from __future__ import annotations

from athanor_api.compiler.models import TransformationSpec, TransformOperation


def _render_operation(op: TransformOperation, expr: str) -> str:
    if op.op == "uppercase":
        return f"{expr}.upper()"
    if op.op == "lowercase":
        return f"{expr}.lower()"
    if op.op == "strip":
        return f"{expr}.strip()"
    if op.op == "reverse":
        return f"{expr}[::-1]"
    if op.op == "prefix":
        value = repr(op.value or "")
        return f"{value} + {expr}"
    if op.op == "suffix":
        value = repr(op.value or "")
        return f"{expr} + {value}"
    if op.op == "replace":
        old = repr(op.old or "")
        new = repr(op.new or "")
        return f"{expr}.replace({old}, {new})"
    return expr


def generate_python_source(spec: TransformationSpec, *, provenance: list[str] | None = None) -> str:
    lines: list[str] = [
        '"""Compiled transformation module.',
        "",
    ]
    if provenance:
        lines.append("Generated from nodes:")
        for node_id in provenance:
            lines.append(f"- {node_id}")
        lines.append("")
    lines.extend(
        [
            "Generated by AthanorIDE NL compiler from TransformationSpec.",
            '"""',
            "",
            "",
            f"def {spec.function_name}({spec.input_name}: str) -> str:",
            '    """Apply the compiled transformation steps."""',
            f"    result = {spec.input_name}",
        ]
    )
    for op in spec.operations:
        lines.append(f"    result = {_render_operation(op, 'result')}")
    lines.append("    return result")
    lines.append("")
    return "\n".join(lines)


def generate_test_source(spec: TransformationSpec, *, sample_input: str = "Hello World") -> str:
    # Compute expected locally for the generated test using the same ops (not executing user code).
    expected = sample_input
    for op in spec.operations:
        if op.op == "uppercase":
            expected = expected.upper()
        elif op.op == "lowercase":
            expected = expected.lower()
        elif op.op == "strip":
            expected = expected.strip()
        elif op.op == "reverse":
            expected = expected[::-1]
        elif op.op == "prefix":
            expected = (op.value or "") + expected
        elif op.op == "suffix":
            expected = expected + (op.value or "")
        elif op.op == "replace":
            expected = expected.replace(op.old or "", op.new or "")

    return "\n".join(
        [
            '"""Generated unit test for compiled transform."""',
            "",
            "from transform import transform",
            "",
            "",
            "def test_transform_sample() -> None:",
            f"    assert transform({sample_input!r}) == {expected!r}",
            "",
        ]
    )
