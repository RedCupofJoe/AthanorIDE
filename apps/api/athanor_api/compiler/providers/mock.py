"""Deterministic mock model provider (no external API credentials)."""

from __future__ import annotations

from typing import Any

from athanor_api.compiler.models import TransformationSpec, TransformOperation
from athanor_api.compiler.providers.base import ModelProvider


def _ops_from_instruction(instruction: str) -> list[TransformOperation]:
    text = instruction.casefold()
    ops: list[TransformOperation] = []

    if "strip" in text or "trim" in text:
        ops.append(TransformOperation(op="strip"))
    if "uppercase" in text or "upper case" in text or "upper-case" in text:
        ops.append(TransformOperation(op="uppercase"))
    if "lowercase" in text or "lower case" in text or "lower-case" in text:
        ops.append(TransformOperation(op="lowercase"))
    if "reverse" in text:
        ops.append(TransformOperation(op="reverse"))

    prefix = _extract_quoted(text, ("prefix with", "add prefix", "prepend"))
    if prefix is not None:
        ops.append(TransformOperation(op="prefix", value=prefix))
    suffix = _extract_quoted(text, ("suffix with", "add suffix", "append"))
    if suffix is not None:
        ops.append(TransformOperation(op="suffix", value=suffix))

    if "replace" in text:
        # Deterministic demo: replace spaces with underscores when mentioned.
        if "space" in text and "underscore" in text:
            ops.append(TransformOperation(op="replace", old=" ", new="_"))

    if not ops:
        ops.append(TransformOperation(op="identity"))
    return ops


def _extract_quoted(text: str, markers: tuple[str, ...]) -> str | None:
    for marker in markers:
        idx = text.find(marker)
        if idx < 0:
            continue
        tail = text[idx + len(marker) :].strip()
        if tail.startswith(("'", '"')):
            quote = tail[0]
            end = tail.find(quote, 1)
            if end > 1:
                return tail[1:end]
        # Fallback token
        token = tail.split()[0] if tail.split() else None
        if token:
            return token.strip(".,;")
    return None


class MockModelProvider(ModelProvider):
    """Deterministic provider used for Phase 3 pipeline testing."""

    name = "mock"

    def generate_spec(
        self,
        *,
        instruction: str,
        input_schema: dict[str, Any],
        output_schema: dict[str, Any],
    ) -> TransformationSpec:
        del input_schema, output_schema
        ops = _ops_from_instruction(instruction)
        return TransformationSpec(
            operations=ops,
            notes=[
                "Generated by MockModelProvider",
                f"Instruction length={len(instruction)}",
            ],
        )

    def correct_spec(
        self,
        *,
        instruction: str,
        input_schema: dict[str, Any],
        output_schema: dict[str, Any],
        previous_spec: TransformationSpec,
        previous_code: str,
        error_stage: str,
        error_message: str,
    ) -> TransformationSpec:
        del previous_code, input_schema, output_schema
        # Visible, bounded correction: drop unsupported ops and fall back to strip+identity.
        safe_ops = [
            op
            for op in previous_spec.operations
            if op.op in {"uppercase", "lowercase", "strip", "identity", "reverse"}
        ]
        if not safe_ops:
            safe_ops = [TransformOperation(op="strip"), TransformOperation(op="identity")]
        return TransformationSpec(
            operations=safe_ops,
            notes=[
                *previous_spec.notes,
                f"Correction after {error_stage}: {error_message[:200]}",
                f"Re-derived from instruction ({len(instruction)} chars)",
            ],
        )


def get_default_provider() -> ModelProvider:
    return MockModelProvider()
